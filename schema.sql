create extension if not exists pgcrypto;

create table if not exists public.allowed_logins (
  login text primary key,
  name text not null,
  role text not null default 'employee' check (role in ('employee','mentor')),
  group_name text not null default 'Группа',
  active boolean not null default true,
  claimed_user_id uuid unique,
  invite_code_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  login text unique not null references public.allowed_logins(login) on update cascade,
  name text not null,
  role text not null check (role in ('employee','mentor')),
  group_name text not null default 'Группа',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.content (
  id uuid primary key default gen_random_uuid(),
  type text not null default 'quiz' check (type in ('quiz','hardcase','dialogue')),
  status text not null default 'draft' check (status in ('draft','published')),
  section text not null check (section in ('soft','hard','needs')),
  topic text not null,
  difficulty text not null default 'Средний',
  title text not null default '',
  payload jsonb not null default '{}'::jsonb,
  audience text[] not null default array['ALL']::text[],
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.assignments (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  content_id uuid references public.content(id) on delete set null,
  section text,
  topic text,
  due date,
  target integer not null default 90 check (target between 0 and 100),
  recipients text[] not null default array['ALL']::text[],
  status text not null default 'active' check (status in ('active','inactive')),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  login text not null,
  created_at timestamptz not null default now(),
  section text not null,
  topic text not null,
  score numeric not null,
  type text not null default 'quiz',
  cpm integer not null default 0
);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  login text not null,
  title text not null,
  body text not null,
  kind text not null default 'info',
  read boolean not null default false,
  created_at timestamptz not null default now()
);

-- The first successfully registered SkillHub user becomes the mentor automatically.
-- Employees are added later by the mentor from the interface or Excel import.

create or replace function public.current_login()
returns text language sql stable security definer set search_path=public
as $$ select login from public.profiles where id=auth.uid() $$;

create or replace function public.is_active_user()
returns boolean language sql stable security definer set search_path=public
as $$ select coalesce((select active from public.profiles where id=auth.uid()),false) $$;

create or replace function public.is_mentor()
returns boolean language sql stable security definer set search_path=public
as $$ select coalesce((select role='mentor' and active from public.profiles where id=auth.uid()),false) $$;

-- Creates a profile only for pre-approved corporate logins.
-- The first account created in a fresh project becomes the mentor.
-- Other employees must first receive a code generated by the mentor in SkillHub.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_login text := lower(trim(coalesce(new.raw_user_meta_data->>'login','')));
  v_code text := coalesce(new.raw_user_meta_data->>'invite_code','');
  a public.allowed_logins%rowtype;
  v_count bigint;
begin
  if v_login='' then
    raise exception 'LOGIN_REQUIRED';
  end if;

  select count(*) into v_count from public.allowed_logins;

  -- Fresh project: the very first account becomes the mentor.
  if v_count=0 then
    insert into public.allowed_logins(login,name,role,group_name,active,claimed_user_id)
    values(v_login,v_login,'mentor','Группа',true,new.id);
    insert into public.profiles(id,login,name,role,group_name,active)
    values(new.id,v_login,v_login,'mentor','Группа',true);
    return new;
  end if;

  select * into a from public.allowed_logins where login=v_login and active=true for update;
  if not found then
    raise exception 'LOGIN_NOT_ALLOWED';
  end if;
  if a.claimed_user_id is not null and a.claimed_user_id <> new.id then
    raise exception 'LOGIN_ALREADY_CLAIMED';
  end if;
  if a.invite_code_hash is null then
    raise exception 'INVITE_CODE_NOT_SET';
  end if;
  if crypt(v_code,a.invite_code_hash) <> a.invite_code_hash then
    raise exception 'BAD_INVITE_CODE';
  end if;
  insert into public.profiles(id,login,name,role,group_name,active)
  values(new.id,a.login,a.name,a.role,a.group_name,a.active)
  on conflict(id) do update set login=excluded.login,name=excluded.name,role=excluded.role,group_name=excluded.group_name,active=excluded.active,updated_at=now();
  update public.allowed_logins set claimed_user_id=new.id,updated_at=now() where login=a.login;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

-- Mentor-only user management.
create or replace function public.mentor_upsert_allowed_user(
  p_login text, p_name text default null, p_role text default 'employee',
  p_group_name text default 'Группа', p_active boolean default true, p_invite_code text default null
) returns table(login text, claimed boolean)
language plpgsql security definer set search_path=public
as $$
declare v_login text:=lower(trim(p_login)); v_claimed uuid;
begin
  if not public.is_mentor() then raise exception 'FORBIDDEN'; end if;
  if v_login='' then raise exception 'LOGIN_REQUIRED'; end if;
  if p_role not in ('employee','mentor') then raise exception 'BAD_ROLE'; end if;
  insert into public.allowed_logins(login,name,role,group_name,active,invite_code_hash)
  values(v_login,coalesce(nullif(trim(p_name),''),v_login),p_role,coalesce(nullif(trim(p_group_name),''),'Группа'),p_active,
         case when p_invite_code is null or p_invite_code='' then null else crypt(p_invite_code,gen_salt('bf')) end)
  on conflict(login) do update set
    name=excluded.name, role=excluded.role, group_name=excluded.group_name, active=excluded.active,
    invite_code_hash=case when p_invite_code is null or p_invite_code='' then public.allowed_logins.invite_code_hash else crypt(p_invite_code,gen_salt('bf')) end,
    updated_at=now();
  select claimed_user_id into v_claimed from public.allowed_logins where allowed_logins.login=v_login;
  if v_claimed is not null then
    update public.profiles set name=coalesce(nullif(trim(p_name),''),v_login),role=p_role,group_name=coalesce(nullif(trim(p_group_name),''),'Группа'),active=p_active,updated_at=now() where id=v_claimed;
  end if;
  return query select v_login,(v_claimed is not null);
end;
$$;

create or replace function public.mentor_set_invite_code(p_login text,p_code text)
returns void language plpgsql security definer set search_path=public
as $$
begin
  if not public.is_mentor() then raise exception 'FORBIDDEN'; end if;
  if length(trim(p_code))<4 then raise exception 'CODE_TOO_SHORT'; end if;
  update public.allowed_logins set invite_code_hash=crypt(trim(p_code),gen_salt('bf')),updated_at=now() where login=lower(trim(p_login));
end;
$$;

create or replace function public.mentor_reset_access(p_login text,p_new_code text)
returns void language plpgsql security definer set search_path=public,auth
as $$
declare uid uuid;
begin
  if not public.is_mentor() then raise exception 'FORBIDDEN'; end if;
  select claimed_user_id into uid from public.allowed_logins where login=lower(trim(p_login));
  if uid is not null then delete from auth.users where id=uid; end if;
  update public.allowed_logins set claimed_user_id=null,invite_code_hash=crypt(trim(p_new_code),gen_salt('bf')),updated_at=now() where login=lower(trim(p_login));
end;
$$;

