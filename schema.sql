-- Drop/recreate policies to make the script safely re-runnable.
do $$ declare r record; begin
 for r in select schemaname,tablename,policyname from pg_policies where schemaname='public' and tablename in ('allowed_logins','profiles','content','assignments','attempts','notifications') loop
   execute format('drop policy if exists %I on %I.%I',r.policyname,r.schemaname,r.tablename);
 end loop;
end $$;

create policy allowed_logins_mentor_select on public.allowed_logins for select to authenticated using (public.is_mentor());

create policy profiles_select on public.profiles for select to authenticated using (id=auth.uid() or public.is_mentor());

create policy content_select on public.content for select to authenticated using (
  public.is_active_user() and (
    public.is_mentor() or (status='published' and ('ALL'=any(audience) or public.current_login()=any(audience)))
  )
);
create policy content_insert on public.content for insert to authenticated with check (public.is_mentor());
create policy content_update on public.content for update to authenticated using (public.is_mentor()) with check (public.is_mentor());
create policy content_delete on public.content for delete to authenticated using (public.is_mentor());

create policy assignments_select on public.assignments for select to authenticated using (
  public.is_active_user() and (public.is_mentor() or ('ALL'=any(recipients) or public.current_login()=any(recipients)))
);
create policy assignments_insert on public.assignments for insert to authenticated with check (public.is_mentor());
create policy assignments_update on public.assignments for update to authenticated using (public.is_mentor()) with check (public.is_mentor());
create policy assignments_delete on public.assignments for delete to authenticated using (public.is_mentor());

create policy attempts_select on public.attempts for select to authenticated using (user_id=auth.uid() or public.is_mentor());
create policy attempts_insert on public.attempts for insert to authenticated with check (user_id=auth.uid() and public.is_active_user());
create policy attempts_delete on public.attempts for delete to authenticated using (public.is_mentor());

create policy notifications_select on public.notifications for select to authenticated using (login=public.current_login() or public.is_mentor());
create policy notifications_insert on public.notifications for insert to authenticated with check (public.is_mentor());
create policy notifications_update on public.notifications for update to authenticated using (login=public.current_login() or public.is_mentor()) with check (login=public.current_login() or public.is_mentor());
create policy notifications_delete on public.notifications for delete to authenticated using (public.is_mentor());

